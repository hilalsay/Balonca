"""Builds tests/grammar-gold/{nl,en}.jsonl from compact notation and checks it.

Part notation: "Ik=S / woon=V / in Utrecht=A"; a digit after the role is the clause id ("dat=L1").
Roles: S subject, V verb (finite), VP verbPart, O object, I indirect, C complement, A adverbial,
L link, N negation, X other.
"""
import json, re, sys, collections

ROLE = {'S': 'subject', 'V': 'verb', 'VP': 'verbPart', 'O': 'object', 'I': 'indirect', 'C': 'complement',
        'A': 'adverbial', 'L': 'link', 'N': 'negation', 'X': 'other'}
CLAUSE_KINDS = {'main', 'sub', 'relative', 'coord'}
NOTE_KINDS = {'tense', 'imperative', 'question', 'whQuestion', 'inversion', 'bracket', 'verbFinal', 'separable',
              'modal', 'passive', 'negation', 'relative', 'teInf', 'reflexive', 'degree', 'articles'}
TENSES = {'present', 'past', 'perfect', 'pluperfect', 'future', 'conditional', 'presentCont', 'pastCont'}

def parts(s):
    out = []
    for p in s.split(' / '):
        text, code = p.rsplit('=', 1)
        m = re.fullmatch(r'([A-Z]+?)(\d?)', code)
        role, cl = m.group(1), int(m.group(2) or 0)
        out.append([text, ROLE[role], cl])
    return out

