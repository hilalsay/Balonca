def note_ok(n):
    kind, *rest = n.split(':', 1)
    if kind not in NOTE_KINDS: return False
    if kind == 'tense' and rest:
        t = rest[0].split(':')[0]
        return t in TENSES
    return True

def build(lang, rows):
    out, errors, seen = [], [], set()
    for (i, text, kinds, ps, notes, must_not, optional, tr) in rows:
        level = 'hard' if i.startswith('h') else 'basic'
        rid = f'{lang}-{i}'
        if text in seen: errors.append(f'{rid}: duplicate sentence')
        seen.add(text)
        kinds = kinds.split()
        p = parts(ps)
        strip = lambda s: re.sub(r'[\s.,!?]', '', s)
        if strip(''.join(x[0] for x in p)) != strip(text): errors.append(f'{rid}: parts do not rebuild the sentence')
        if kinds[0] != 'main' or any(k not in CLAUSE_KINDS for k in kinds): errors.append(f'{rid}: bad clause kinds')
        if any(x[2] >= len(kinds) for x in p): errors.append(f'{rid}: part points to missing clause')
        if set(x[2] for x in p) != set(range(len(kinds))): errors.append(f'{rid}: a clause has no parts')
        for c in range(len(kinds)):
            if not any(x[1] == 'verb' for x in p if x[2] == c) and kinds[c] == 'main':
                errors.append(f'{rid}: main clause without a finite verb')
        ns, mn, op = notes.split(), must_not.split(), optional.split()
        for n in ns + mn + op:
            if not note_ok(n): errors.append(f'{rid}: bad note {n}')
        for n in ns:
            if any(n.startswith(m) or m.startswith(n.split(':')[0]) and m == n.split(':')[0] for m in mn):
                errors.append(f'{rid}: {n} is both expected and forbidden')
        out.append({'id': rid, 'lang': lang, 'text': text, 'clauses': kinds, 'parts': p, 'notes': ns,
                    'mustNot': mn, 'optional': op, 'translation_tr': tr, 'level': level, 'checked_by': 'draft'})
    return out, errors

