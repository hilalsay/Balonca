// Bundles src/lib/shared/server.ts into server/gen/shared.mjs (plain ESM, no dependencies) for the Node server.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
await build({
  entryPoints: [`${root}src/lib/shared/server.ts`], outfile: `${root}server/gen/shared.mjs`,
  bundle: true, format: 'esm', platform: 'node', target: 'node22', logLevel: 'warning',
  banner: { js: '// Generated by scripts/build-shared.mjs from src/lib/shared/server.ts. Do not edit.' },
});
